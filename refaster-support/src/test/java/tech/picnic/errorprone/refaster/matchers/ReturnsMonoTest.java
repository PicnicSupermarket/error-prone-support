package tech.picnic.errorprone.refaster.matchers;

import static com.google.errorprone.BugPattern.SeverityLevel.ERROR;

import com.google.errorprone.BugPattern;
import com.google.errorprone.CompilationTestHelper;
import com.google.errorprone.bugpatterns.BugChecker;
import org.junit.jupiter.api.Test;

final class ReturnsMonoTest {
  @Test
  void matches() {
    CompilationTestHelper.newInstance(MatcherTestChecker.class, getClass())
        .addSourceLines(
            "A.java",
            "import java.util.function.Function;",
            "import java.util.function.Supplier;",
            "import java.util.function.UnaryOperator;",
            "import org.reactivestreams.Publisher;",
            "import reactor.core.publisher.Flux;",
            "import reactor.core.publisher.Mono;",
            "",
            "class A {",
            "  String negative1() {",
            "    return toString();",
            "  }",
            "",
            "  Supplier<Mono<String>> negative2() {",
            "    return () -> Mono.just(\"s\");",
            "  }",
            "",
            "  Supplier<Mono<String>> negative3() {",
            "    return Mono::empty;",
            "  }",
            "",
            "  Supplier<Mono<String>> negative4() {",
            "    return negative4();",
            "  }",
            "",
            "  Function<String, String> negative5() {",
            "    return s -> s;",
            "  }",
            "",
            "  Function<String, String> negative6() {",
            "    return String::valueOf;",
            "  }",
            "",
            "  Function<String, String> negative7() {",
            "    return negative7();",
            "  }",
            "",
            "  Function<String, Publisher<String>> negative8() {",
            "    return s -> Flux.just(s);",
            "  }",
            "",
            "  Function<String, Publisher<String>> negative9() {",
            "    return s -> {",
            "      throw new UnsupportedOperationException();",
            "    };",
            "  }",
            "",
            "  Function<String, Publisher<String>> negative10() {",
            "    return s -> true ? Mono.just(s) : Flux.just(s);",
            "  }",
            "",
            "  Function<String, Publisher<String>> negative11() {",
            "    return s -> {",
            "      if (s.isEmpty()) {",
            "        return Mono.empty();",
            "      }",
            "      return Flux.just(s);",
            "    };",
            "  }",
            "",
            "  Function<String, Publisher<String>> negative12() {",
            "    return Flux::just;",
            "  }",
            "",
            "  Function<String, Publisher<String>> negative13() {",
            "    return negative13();",
            "  }",
            "",
            "  Function<String, Flux<String>> negative14() {",
            "    return s -> Flux.just(s);",
            "  }",
            "",
            "  Function<String, Flux<String>> negative15() {",
            "    return Flux::just;",
            "  }",
            "",
            "  Function<String, Flux<String>> negative16() {",
            "    return negative16();",
            "  }",
            "",
            "  Function<String, Publisher<String>> positive1() {",
            "    // BUG: Diagnostic contains:",
            "    return s -> Mono.just(s);",
            "  }",
            "",
            "  Function<String, Publisher<String>> positive2() {",
            "    // BUG: Diagnostic contains:",
            "    return s -> true ? Mono.just(s) : Mono.empty();",
            "  }",
            "",
            "  Function<String, Publisher<String>> positive3() {",
            "    // BUG: Diagnostic contains:",
            "    return s -> {",
            "      if (s.isEmpty()) {",
            "        return Mono.empty();",
            "      }",
            "      return Mono.just(s);",
            "    };",
            "  }",
            "",
            "  Function<String, Publisher<String>> positive4() {",
            "    // BUG: Diagnostic contains:",
            "    return Mono::just;",
            "  }",
            "",
            "  Function<String, Mono<String>> positive5() {",
            "    // BUG: Diagnostic contains:",
            "    return s -> Mono.just(s);",
            "  }",
            "",
            "  Function<String, Mono<String>> positive6() {",
            "    // BUG: Diagnostic contains:",
            "    return Mono::just;",
            "  }",
            "",
            "  Function<String, Mono<String>> positive7() {",
            "    // BUG: Diagnostic contains:",
            "    return positive7();",
            "  }",
            "",
            "  UnaryOperator<Mono<String>> positive8() {",
            "    // BUG: Diagnostic contains:",
            "    return m -> m;",
            "  }",
            "",
            "  UnaryOperator<Mono<String>> positive9() {",
            "    // BUG: Diagnostic contains:",
            "    return Mono::onErrorComplete;",
            "  }",
            "",
            "  UnaryOperator<Mono<String>> positive10() {",
            "    // BUG: Diagnostic contains:",
            "    return positive10();",
            "  }",
            "}")
        .doTest();
  }

  /** A {@link BugChecker} that simply delegates to {@link ReturnsMono}. */
  @BugPattern(summary = "Flags expressions matched by `ReturnsMono`", severity = ERROR)
  private static final class MatcherTestChecker extends AbstractMatcherTestChecker {
    private static final long serialVersionUID = 1L;

    private MatcherTestChecker() {
      super(new ReturnsMono());
    }
  }
}
