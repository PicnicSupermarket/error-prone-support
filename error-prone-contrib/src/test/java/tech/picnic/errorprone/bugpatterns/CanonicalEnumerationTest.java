package tech.picnic.errorprone.bugpatterns;

import com.google.errorprone.BugCheckerRefactoringTestHelper;
import com.google.errorprone.CompilationTestHelper;
import org.junit.jupiter.api.Test;

final class CanonicalEnumerationTest {
  /**
   * Verifies the expressions flagged by {@link CanonicalEnumeration}.
   *
   * <p>The negative cases are grouped by the construct that rejects them, and the positive cases by
   * the rule that flags them; both follow the order in which these appear in the checker's source.
   */
  @Test
  void identification() {
    CompilationTestHelper.newInstance(CanonicalEnumeration.class, getClass())
        .addSourceLines(
            "A.java",
            "import com.google.common.collect.ImmutableBiMap;",
            "import com.google.common.collect.ImmutableList;",
            "import com.google.common.collect.ImmutableListMultimap;",
            "import com.google.common.collect.ImmutableMap;",
            "import com.google.common.collect.ImmutableMultimap;",
            "import com.google.common.collect.ImmutableMultiset;",
            "import com.google.common.collect.ImmutableSet;",
            "import com.google.common.collect.ImmutableSetMultimap;",
            "import com.google.common.collect.ImmutableSortedMap;",
            "import com.google.common.collect.ImmutableSortedSet;",
            "import com.google.common.collect.Maps;",
            "import io.micrometer.core.instrument.Tag;",
            "import java.util.Comparator;",
            "import java.util.List;",
            "import java.util.Map;",
            "import java.util.Set;",
            "",
            "class A {",
            "  void nonEnumerations() {",
            "    ImmutableList.copyOf(new Integer[] {1});",
            "    ImmutableList.of(1, 2).size();",
            "  }",
            "",
            "  void canonicalEnumerations() {",
            "    ImmutableMap.of(\"foo\", 1);",
            "    ImmutableListMultimap.of(\"foo\", 1);",
            "  }",
            "",
            "  void nonTagEnumerations() {",
            "    ImmutableList.of(1, 2);",
            "    ImmutableSet.of(1, 2);",
            "  }",
            "",
            "  void emptyTagEnumeration() {",
            "    consumeTags(ImmutableList.of());",
            "  }",
            "",
            "  private static void consumeTags(Iterable<? extends Tag> tags) {}",
            "",
            "  void unsupportedBuilderInvocations() {",
            "    ImmutableList.builder().add(1).addAll(ImmutableList.of(2)).build();",
            "    ImmutableMap.builder().put(\"foo\", 1).buildKeepingLast();",
            "    ImmutableMap.<String, Integer>builder()",
            "        .orderEntriesByValue(Comparator.naturalOrder())",
            "        .put(\"foo\", 1)",
            "        .buildOrThrow();",
            "    ImmutableSortedSet.orderedBy(Comparator.<Integer>naturalOrder()).add(1).build();",
            "    ImmutableSortedSet.<Integer>reverseOrder().add(1).build();",
            "  }",
            "",
            "  void nonFluentBuilder() {",
            "    ImmutableList.Builder<Integer> builder = ImmutableList.builder();",
            "    builder.add(1);",
            "    builder.build();",
            "  }",
            "",
            "  void partialBuilderEntries() {",
            "    ImmutableMap.builder().put(Map.entry(\"foo\", 1)).buildOrThrow();",
            "    ImmutableMap.builder().put(Map.entry(\"foo\", 1)).put(Map.entry(\"bar\", 2)).build();",
            "  }",
            "",
            "  void nonLiteralMapEntries() {",
            "    Map.Entry<String, Integer> entry = Map.entry(\"foo\", 1);",
            "    Map.ofEntries(entry);",
            "    ImmutableMap.ofEntries(entry);",
            "    Map.ofEntries(createEntry());",
            "  }",
            "",
            "  private static Map.Entry<String, Integer> createEntry() {",
            "    return Map.entry(\"foo\", 1);",
            "  }",
            "",
            "  void unorderedStreamSources() {",
            "    ImmutableSet.of(1, 2).stream();",
            "    ImmutableMultiset.of(1, 2).stream();",
            "  }",
            "",
            "  interface B extends java.util.Collection<Integer> {",
            "    default void receiverlessStream() {",
            "      stream();",
            "    }",
            "  }",
            "",
            "  void arraysPassedToVarargsParameters() {",
            "    List.<Integer>of(new Integer[] {1});",
            "    ImmutableList.<Integer>builder().add(new Integer[] {1}).build();",
            "  }",
            "",
            "  void unsupportedArities() {",
            "    ImmutableListMultimap.builder()",
            "        .put(\"foo\", 1)",
            "        .put(\"bar\", 2)",
            "        .put(\"baz\", 3)",
            "        .put(\"qux\", 4)",
            "        .put(\"quux\", 5)",
            "        .put(\"corge\", 6)",
            "        .build();",
            "  }",
            "",
            "  void unsupportedElementTypes() {",
            "    ImmutableSortedSet.<Object>builder().add(new Object()).build();",
            "    ImmutableSortedMap.<Object, Integer>builder().put(new Object(), 1).build();",
            "  }",
            "",
            "  <T extends Comparable<?>> ImmutableSortedSet<T> selfIncomparableElements(T value) {",
            "    return ImmutableSortedSet.<T>naturalOrder().add(value).build();",
            "  }",
            "",
            "  <K extends Comparable<?>> ImmutableSortedMap<K, Integer> selfIncomparableKeys(K key) {",
            "    return ImmutableSortedMap.<K, Integer>naturalOrder().put(key, 1).build();",
            "  }",
            "",
            "  void jdkFactoryMethods() {",
            "    // BUG: Diagnostic contains:",
            "    List.of();",
            "    // BUG: Diagnostic contains:",
            "    List.of(1, 2, 3);",
            "    // BUG: Diagnostic contains:",
            "    Map.of(\"foo\", 1, \"bar\", 2);",
            "    // BUG: Diagnostic contains:",
            "    Set.of(4, 5, 6);",
            "    // Six elements are accepted only by `ImmutableSet#of`'s varargs overload.",
            "    // BUG: Diagnostic contains:",
            "    Set.of(7, 8, 9, 10, 11, 12);",
            "  }",
            "",
            "  void mapEntryEnumerations() {",
            "    // BUG: Diagnostic contains:",
            "    Map.ofEntries(Map.entry(\"foo\", 1), Map.entry(\"bar\", 2));",
            "    // BUG: Diagnostic contains:",
            "    ImmutableMap.ofEntries(Maps.immutableEntry(\"baz\", 3));",
            "  }",
            "",
            "  void multimapFactoryMethod() {",
            "    // BUG: Diagnostic contains:",
            "    ImmutableMultimap.of(\"foo\", 1);",
            "  }",
            "",
            "  void micrometerTags() {",
            "    // BUG: Diagnostic contains:",
            "    ImmutableList.of(Tag.of(\"foo\", \"bar\"));",
            "    // BUG: Diagnostic contains:",
            "    ImmutableSet.of(Tag.of(\"baz\", \"qux\"), Tag.of(\"quux\", \"corge\"));",
            "  }",
            "",
            "  void streamedEnumerations() {",
            "    // Note that the streamed sub-expressions are flagged as well.",
            "    // BUG: Diagnostic contains:",
            "    List.of(1, 2).stream();",
            "    // BUG: Diagnostic contains:",
            "    ImmutableList.of(3, 4).stream();",
            "    // BUG: Diagnostic contains:",
            "    ImmutableList.builder().add(5).build().stream();",
            "  }",
            "",
            "  void builderChains() {",
            "    // BUG: Diagnostic contains:",
            "    ImmutableBiMap.builder().put(\"foo\", 1).buildOrThrow();",
            "    // BUG: Diagnostic contains:",
            "    ImmutableList.builder().build();",
            "    // BUG: Diagnostic contains:",
            "    ImmutableList.builder().add(2).add(3, 4).build();",
            "    // BUG: Diagnostic contains:",
            "    ImmutableListMultimap.builderWithExpectedKeys(1).put(\"bar\", 5).build();",
            "    // BUG: Diagnostic contains:",
            "    ImmutableMap.builderWithExpectedSize(1).put(\"baz\", 6).buildOrThrow();",
            "    // BUG: Diagnostic contains:",
            "    ImmutableMultiset.builder().add(7).build();",
            "    // BUG: Diagnostic contains:",
            "    ImmutableSet.builder().add(8).build();",
            "    // BUG: Diagnostic contains:",
            "    ImmutableSetMultimap.builder().put(\"qux\", 9).build();",
            "    // BUG: Diagnostic contains:",
            "    ImmutableSortedMap.<String, Integer>naturalOrder().put(\"quux\", 10).build();",
            "    // BUG: Diagnostic contains:",
            "    ImmutableSortedSet.<Integer>naturalOrder().add(11).build();",
            "  }",
            "",
            "  <T extends Comparable<? super T>> ImmutableSortedSet<T> selfComparableElements(T v) {",
            "    // BUG: Diagnostic contains:",
            "    return ImmutableSortedSet.<T>naturalOrder().add(v).build();",
            "  }",
            "",
            "  <K extends Comparable<? super K>> ImmutableSortedMap<K, Integer> selfComparableKeys(K key) {",
            "    // BUG: Diagnostic contains:",
            "    return ImmutableSortedMap.<K, Integer>naturalOrder().put(key, 1).build();",
            "  }",
            "}")
        .doTest();
  }

  /**
   * Verifies that the check does not depend on the target types being referenced by another source
   * file in the same compilation.
   */
  @Test
  void identificationWithoutGuavaReferencesInSource() {
    CompilationTestHelper.newInstance(CanonicalEnumeration.class, getClass())
        .addSourceLines(
            "A.java",
            "import java.util.List;",
            "",
            "class A {",
            "  Object m() {",
            "    // BUG: Diagnostic contains:",
            "    return List.of(1, 2);",
            "  }",
            "}")
        .doTest();
  }

  @Test
  void identificationWithoutGuavaOnClasspath() {
    CompilationTestHelper.newInstance(CanonicalEnumeration.class, getClass())
        .withClasspath()
        .addSourceLines(
            "A.java",
            "import java.util.List;",
            "import java.util.Map;",
            "import java.util.Set;",
            "",
            "class A {",
            "  void m() {",
            "    List.of(1, 2);",
            "    Map.of(\"foo\", 3);",
            "    Set.of(4, 5);",
            "    Map.ofEntries(Map.entry(\"bar\", 6));",
            "    // Enumerations that target a JDK type are still flagged.",
            "    // BUG: Diagnostic contains:",
            "    List.of(7, 8).stream();",
            "  }",
            "}")
        .doTest();
  }

  @Test
  void replacement() {
    BugCheckerRefactoringTestHelper.newInstance(CanonicalEnumeration.class, getClass())
        .addInputLines(
            "A.java",
            "import com.google.common.collect.ImmutableList;",
            "import com.google.common.collect.ImmutableMap;",
            "import com.google.common.collect.ImmutableMultimap;",
            "import com.google.common.collect.ImmutableSortedSet;",
            "import io.micrometer.core.instrument.Tag;",
            "import java.util.List;",
            "import java.util.Map;",
            "import java.util.Set;",
            "",
            "class A {",
            "  void m() {",
            "    List.of();",
            "    List.of(1, /* Second element. */ 2);",
            "    Map.of(\"foo\", 3);",
            "    Set.of(4, 5);",
            "    Map.ofEntries(Map.entry(\"bar\", 6), Map.entry(\"baz\", 7));",
            "    ImmutableMultimap.of(\"qux\", 8);",
            "    ImmutableList.of(Tag.of(\"quux\", \"corge\"));",
            "    ImmutableList.of(9, 10).stream();",
            "    ImmutableList.builder().add(11).add(12, 13).build();",
            "    ImmutableMap.builderWithExpectedSize(1).put(\"grault\", 14).buildOrThrow();",
            "    ImmutableSortedSet.<Integer>naturalOrder().add(15).build();",
            "  }",
            "}")
        .addOutputLines(
            "A.java",
            "import com.google.common.collect.ImmutableList;",
            "import com.google.common.collect.ImmutableListMultimap;",
            "import com.google.common.collect.ImmutableMap;",
            "import com.google.common.collect.ImmutableMultimap;",
            "import com.google.common.collect.ImmutableSet;",
            "import com.google.common.collect.ImmutableSortedSet;",
            "import io.micrometer.core.instrument.Tag;",
            "import io.micrometer.core.instrument.Tags;",
            "import java.util.List;",
            "import java.util.Map;",
            "import java.util.Set;",
            "import java.util.stream.Stream;",
            "",
            "class A {",
            "  void m() {",
            "    ImmutableList.of();",
            "    ImmutableList.of(1, 2);",
            "    ImmutableMap.of(\"foo\", 3);",
            "    ImmutableSet.of(4, 5);",
            "    ImmutableMap.of(\"bar\", 6, \"baz\", 7);",
            "    ImmutableListMultimap.of(\"qux\", 8);",
            "    Tags.of(Tag.of(\"quux\", \"corge\"));",
            "    Stream.of(9, 10);",
            "    ImmutableList.of(11, 12, 13);",
            "    ImmutableMap.of(\"grault\", 14);",
            "    ImmutableSortedSet.of(15);",
            "  }",
            "}")
        .doTest();
  }
}
