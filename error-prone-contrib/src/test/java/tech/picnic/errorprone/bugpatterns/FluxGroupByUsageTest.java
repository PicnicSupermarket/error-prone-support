package tech.picnic.errorprone.bugpatterns;

import com.google.errorprone.CompilationTestHelper;
import org.junit.jupiter.api.Test;

final class FluxGroupByUsageTest {
  @Test
  void identification() {
    CompilationTestHelper.newInstance(FluxGroupByUsage.class, getClass())
        .addSourceLines(
            "A.java",
            "import java.math.RoundingMode;",
            "import java.util.function.BiFunction;",
            "import java.util.function.Function;",
            "import reactor.core.publisher.Flux;",
            "import reactor.core.publisher.GroupedFlux;",
            "",
            "class A {",
            "  <E extends Enum<E>> void m() {",
            "    new NonFlux().groupBy(Object::toString);",
            "    Flux.just(1).groupBy(i -> true);",
            "    Flux.just(2).publish().groupBy(i -> false);",
            "    Flux.just(3).groupBy(i -> true, 1);",
            "    Flux.just(4).publish().groupBy(i -> false, 1);",
            "    Flux.just(5).groupBy(i -> true, Object::toString);",
            "    Flux.just(6).publish().groupBy(i -> false, Object::toString);",
            "    Flux.just(7).groupBy(i -> true, Object::toString, 1);",
            "    Flux.just(8).publish().groupBy(i -> false, Object::toString, 1);",
            "    Flux.just(9).groupBy(i -> RoundingMode.UP);",
            "    Flux.just(10).groupBy(i -> RoundingMode.UP, Object::toString);",
            "    Flux.just(11).groupBy(new EnumMapper());",
            "    Flux.just(12).groupBy((Function<Integer, ? extends Boolean>) i -> true);",
            "    Flux.just(13).groupBy((Function<Integer, ? extends RoundingMode>) i -> RoundingMode.UP);",
            "    Flux.just(14).groupBy(i -> (E) null);",
            "    Flux.just(15).groupBy(i -> (Enum<?>) RoundingMode.UP);",
            "    Flux.just(16).<Object>groupBy(new EnumMapper());",
            "    Flux<GroupedFlux<Object, Integer>> enumMapperGroups = Flux.just(17).groupBy(new EnumMapper());",
            "    Flux<GroupedFlux<Object, Integer>> booleanLambdaGroups = Flux.just(18).groupBy(i -> true);",
            "    Flux<GroupedFlux<Object, Integer>> enumLambdaGroups =",
            "        Flux.just(19).groupBy(i -> RoundingMode.UP);",
            "    Flux<GroupedFlux<Object, Integer>> parenthesizedLambdaGroups =",
            "        Flux.just(20).groupBy((i -> RoundingMode.UP));",
            "    Flux<GroupedFlux<Object, Integer>> conditionalLambdaGroups =",
            "        Flux.just(21).groupBy(i -> i > 0 ? RoundingMode.UP : RoundingMode.DOWN);",
            "    Flux<GroupedFlux<Object, Integer>> blockLambdaGroups =",
            "        Flux.just(22)",
            "            .groupBy(i -> {",
            "              if (i > 0) {",
            "                return RoundingMode.UP;",
            "              }",
            "              return RoundingMode.DOWN;",
            "            });",
            "    Flux<GroupedFlux<Object, Integer>> methodReferenceGroups =",
            "        Flux.just(23).groupBy(new EnumMapper()::apply);",
            "    @SuppressWarnings(\"removal\")",
            "    Flux<GroupedFlux<Object, String>> constructorReferenceGroups =",
            "        Flux.just(\"24\").groupBy(Boolean::new);",
            "",
            "    // BUG: Diagnostic contains:",
            "    Flux.just(25).groupBy(Object::toString);",
            "    // BUG: Diagnostic contains:",
            "    Flux.just(26).publish().groupBy(Object::toString);",
            "    // BUG: Diagnostic contains:",
            "    Flux.just(27).groupBy(Object::toString, 1);",
            "    // BUG: Diagnostic contains:",
            "    Flux.just(28).publish().groupBy(Object::toString, 1);",
            "    // BUG: Diagnostic contains:",
            "    Flux.just(29).groupBy(Object::toString, i -> true);",
            "    // BUG: Diagnostic contains:",
            "    Flux.just(30).publish().groupBy(Object::toString, i -> true);",
            "    // BUG: Diagnostic contains:",
            "    Flux.just(31).groupBy(Object::toString, i -> true, 1);",
            "    // BUG: Diagnostic contains:",
            "    Flux.just(32).publish().groupBy(Object::toString, i -> true, 1);",
            "    // BUG: Diagnostic contains:",
            "    Flux.just(33).groupBy(i -> \"foo\");",
            "    // BUG: Diagnostic contains:",
            "    Flux.just(34).groupBy(Function.identity());",
            "    Flux<GroupedFlux<Object, Integer>> mixedConditionalLambdaGroups =",
            "        // BUG: Diagnostic contains:",
            "        Flux.just(35).groupBy(i -> i > 0 ? RoundingMode.UP : \"foo\");",
            "",
            "    this.<Integer, RoundingMode>sink(Flux::groupBy);",
            "    Function<Function<Integer, RoundingMode>, Object> boundEnumGrouper = Flux.just(36)::groupBy;",
            "    Function<EnumMapper, Object> boundObjectKeyGrouper = Flux.just(37)::<Object>groupBy;",
            "",
            "    // BUG: Diagnostic contains:",
            "    this.<Integer, String>sink(Flux::groupBy);",
            "    BiFunction<Function<Integer, String>, Function<Integer, RoundingMode>, Object>",
            "        boundStringGrouper =",
            "            // BUG: Diagnostic contains:",
            "            Flux.just(38)::groupBy;",
            "  }",
            "",
            "  private <T, K> void sink(BiFunction<Flux<T>, Function<T, K>, Object> fun) {}",
            "",
            "  class EnumMapper implements Function<Integer, RoundingMode> {",
            "    @Override",
            "    public RoundingMode apply(Integer value) {",
            "      return RoundingMode.UP;",
            "    }",
            "  }",
            "",
            "  class NonFlux {",
            "    void groupBy(Function<Integer, String> keyMapper) {}",
            "  }",
            "}")
        .doTest();
  }
}
