package tech.picnic.errorprone.bugpatterns;

import com.google.errorprone.BugCheckerRefactoringTestHelper;
import com.google.errorprone.CompilationTestHelper;
import org.junit.jupiter.api.Test;

final class DuplicateAnnotationAttributeListingTest {
  @Test
  void identification() {
    CompilationTestHelper.newInstance(DuplicateAnnotationAttributeListing.class, getClass())
        .addSourceLines(
            "A.java",
            "import static java.lang.annotation.ElementType.TYPE;",
            "",
            "import java.lang.annotation.ElementType;",
            "",
            "interface A {",
            "  String CONSTANT = \"a\";",
            "",
            "  @interface Foo {",
            "    String[] value() default {};",
            "",
            "    int[] ints() default {};",
            "",
            "    Class<?>[] cls() default {};",
            "",
            "    ElementType[] enums() default {};",
            "",
            "    Bar[] anns() default {};",
            "  }",
            "",
            "  @interface Bar {",
            "    String[] value() default {};",
            "  }",
            "",
            "  @Foo(\"a\")",
            "  A singleton();",
            "",
            "  @Foo({})",
            "  A empty();",
            "",
            "  @Foo({\"a\", \"A\"})",
            "  A distinctStrings();",
            "",
            "  @Foo(ints = {'1', 1})",
            "  A distinctInts();",
            "",
            "  @Foo(cls = {int.class, String.class})",
            "  A distinctClasses();",
            "",
            "  @Foo(enums = {ElementType.TYPE, ElementType.METHOD})",
            "  A distinctEnums();",
            "",
            "  @Foo(anns = {@Bar(\"a\"), @Bar({\"a\", \"b\"})})",
            "  A distinctAnns();",
            "",
            "  // BUG: Diagnostic contains:",
            "  @Foo({\"a\", CONSTANT})",
            "  A duplicateStrings();",
            "",
            "  // BUG: Diagnostic contains:",
            "  @Foo(ints = {'1', 49})",
            "  A duplicateInts();",
            "",
            "  // BUG: Diagnostic contains:",
            "  @Foo(cls = {String.class, java.lang.String.class})",
            "  A duplicateClasses();",
            "",
            "  // BUG: Diagnostic contains:",
            "  @Foo(enums = {TYPE, ElementType.TYPE})",
            "  A duplicateEnums();",
            "",
            "  // BUG: Diagnostic contains:",
            "  @Foo(anns = {@Bar(\"a\"), @Bar({\"a\"})})",
            "  A duplicateAnns();",
            "",
            "  // BUG: Diagnostic contains:",
            "  @Foo(anns = {@Bar({\"a\", \"a\"})})",
            "  A duplicateNestedStrings();",
            "}")
        .doTest();
  }

  @Test
  void replacement() {
    BugCheckerRefactoringTestHelper.newInstance(
            DuplicateAnnotationAttributeListing.class, getClass())
        .addInputLines(
            "A.java",
            "import java.lang.annotation.ElementType;",
            "",
            "interface A {",
            "  String CONSTANT = \"a\";",
            "",
            "  @interface Foo {",
            "    String[] value() default {};",
            "",
            "    ElementType[] enums() default {};",
            "",
            "    Bar[] anns() default {};",
            "  }",
            "",
            "  @interface Bar {",
            "    String[] value() default {};",
            "  }",
            "",
            "  @Foo({\"b\", \"a\", \"b\", \"c\", \"a\"})",
            "  A duplicateStrings();",
            "",
            "  @Foo({\"a\", CONSTANT})",
            "  A duplicateConstants();",
            "",
            "  @Foo(",
            "      value = {\"a\", \"a\"},",
            "      enums = {ElementType.TYPE, ElementType.METHOD, ElementType.TYPE})",
            "  A duplicatesInMultipleAttributes();",
            "",
            "  @Foo(anns = {@Bar(\"a\"), @Bar({\"b\"}), @Bar(\"a\")})",
            "  A duplicateAnns();",
            "}")
        .addOutputLines(
            "A.java",
            "import java.lang.annotation.ElementType;",
            "",
            "interface A {",
            "  String CONSTANT = \"a\";",
            "",
            "  @interface Foo {",
            "    String[] value() default {};",
            "",
            "    ElementType[] enums() default {};",
            "",
            "    Bar[] anns() default {};",
            "  }",
            "",
            "  @interface Bar {",
            "    String[] value() default {};",
            "  }",
            "",
            "  @Foo({\"b\", \"a\", \"c\"})",
            "  A duplicateStrings();",
            "",
            "  @Foo({\"a\"})",
            "  A duplicateConstants();",
            "",
            "  @Foo(",
            "      value = {\"a\"},",
            "      enums = {ElementType.TYPE, ElementType.METHOD})",
            "  A duplicatesInMultipleAttributes();",
            "",
            "  @Foo(anns = {@Bar(\"a\"), @Bar({\"b\"})})",
            "  A duplicateAnns();",
            "}")
        .doTest();
  }

  @Test
  void filtering() {
    CompilationTestHelper.newInstance(DuplicateAnnotationAttributeListing.class, getClass())
        .setArgs(
            "-XepOpt:DuplicateAnnotationAttributeListing:Includes=pkg.A.Foo,pkg.A.Bar",
            "-XepOpt:DuplicateAnnotationAttributeListing:Excludes=pkg.A.Bar#value")
        .addSourceLines(
            "pkg/A.java",
            "package pkg;",
            "",
            "interface A {",
            "  @interface Foo {",
            "    String[] value() default {};",
            "",
            "    String[] value2() default {};",
            "  }",
            "",
            "  @interface Bar {",
            "    String[] value() default {};",
            "",
            "    String[] value2() default {};",
            "  }",
            "",
            "  @interface Baz {",
            "    String[] value() default {};",
            "",
            "    String[] value2() default {};",
            "  }",
            "",
            "  @Bar({\"a\", \"a\"})",
            "  A barValue();",
            "",
            "  @Baz({\"a\", \"a\"})",
            "  A bazValue();",
            "",
            "  @Baz(value2 = {\"a\", \"a\"})",
            "  A bazValue2();",
            "",
            "  // BUG: Diagnostic contains:",
            "  @Foo({\"a\", \"a\"})",
            "  A fooValue();",
            "",
            "  // BUG: Diagnostic contains:",
            "  @Foo(value2 = {\"a\", \"a\"})",
            "  A fooValue2();",
            "",
            "  // BUG: Diagnostic contains:",
            "  @Bar(value2 = {\"a\", \"a\"})",
            "  A barValue2();",
            "}")
        .doTest();
  }
}
